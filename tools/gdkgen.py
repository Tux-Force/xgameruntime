#!/usr/bin/env python3
"""gdkgen: code generation and stub bookkeeping for xgameruntime.

All input is our own source: the .idl interface descriptions, the C implementation and Wine logs
of real games. Nothing here reads or reproduces Microsoft binaries.

Commands:
  report [LOG...]   Markdown table of every stub, with how often games hit it (fixme lines in the
                    given Wine logs, run with WINEDEBUG=fixme+gdkc).
  check             Compare each C vtable with its IDL interface: wrong order, unknown entries,
                    methods missing at the end.
  stubs [--write]   Generate C stubs for IDL methods missing at the end of a vtable (new GDK
                    interface versions). Prints them, or inserts them with --write.
  events [--write]  (Re)generate the bodies of the event registrations listed in
                    tools/gdkgen/events.toml. Lists what is out of date (exit 1), or rewrites
                    it with --write.

Run from anywhere; paths are relative to the repository root (the parent of tools/).
"""

import argparse
import re
import sys
import tomllib
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EVENTS = ROOT / "tools" / "gdkgen" / "events.toml"
MARKER = "/* Generated by tools/gdkgen.py (never-fires), see tools/gdkgen/events.toml. */"

FUNC_RE = re.compile(
    r"^static (?P<ret>[A-Za-z_][\w \*]*?)\s*WINAPI (?P<name>\w+)\( *(?P<params>[^)]*?) *\)\n\{\n",
    re.M,
)
VTBL_RE = re.compile(r"static const struct (?P<iface>\w+)Vtbl \w+ =\s*\{(?P<body>.*?)\};", re.S)
IFACE_RE = re.compile(r"^interface (?P<name>\w+)\s*:\s*(?P<base>\w+)\s*\{(?P<body>.*?)^\}", re.S | re.M)
METHOD_RE = re.compile(r"^\s*(?P<ret>[A-Za-z_][\w \*]*?)\s+(?P<name>\w+)\(\s*(?P<params>.*?)\s*\);", re.M | re.S)
TYPEDEF_RE = re.compile(r"typedef\s+(?P<kind>enum|struct|union)?\s*(?P<body>[^;{]*?)(?:\{|;)")


# ---------------------------------------------------------------------------------------------
# Parsing


@dataclass
class Function:
    path: Path
    ret: str
    name: str
    params: str
    start: int  # offset of "static"
    body_start: int  # offset after "{\n"
    end: int  # offset after the closing "}\n"
    text: str

    @property
    def body(self) -> str:
        return self.text[self.body_start : self.end]

    @property
    def method(self) -> str:
        m = re.match(r"^x_[a-z0-9_]+?_(X[A-Za-z0-9]\w*)$", self.name)
        return m.group(1) if m else self.name

    @property
    def is_stub(self) -> bool:
        return "stub!" in self.body

    @property
    def generated(self) -> bool:
        return MARKER in self.body


def c_files() -> list[Path]:
    return sorted(p for p in ROOT.glob("*.c"))


def idl_files() -> list[Path]:
    return sorted(ROOT.glob("*.idl"))


def parse_functions(path: Path) -> list[Function]:
    text = path.read_text()
    out = []
    for m in FUNC_RE.finditer(text):
        end = text.find("\n}\n", m.end() - 2)
        if end < 0:
            continue
        out.append(Function(path, m["ret"].strip(), m["name"], m["params"], m.start(), m.end(), end + 3, text))
    return out


def all_functions() -> list[Function]:
    return [f for p in c_files() for f in parse_functions(p)]


def split_params(params: str) -> list[tuple[str, str]]:
    """'[in] const char *a, UINT32 b' -> [('const char *', 'a'), ('UINT32', 'b')]."""
    params = re.sub(r"\[[^\]]*\]", "", params).strip()
    if not params or params == "void":
        return []
    out = []
    for p in params.split(","):
        p = " ".join(p.split())
        m = re.match(r"^(.*?)(\w+)$", p)
        typ, name = m.group(1).strip(), m.group(2)
        typ = re.sub(r"\s*\*", " *", typ).replace("* *", "**")
        out.append((typ, name))
    return out


@dataclass
class Interface:
    name: str
    base: str
    methods: list[tuple[str, str, str]] = field(default_factory=list)  # (ret, name, params)


def parse_interfaces() -> dict[str, Interface]:
    out = {}
    for path in idl_files():
        text = re.sub(r"/\*.*?\*/", "", path.read_text(), flags=re.S)
        for m in IFACE_RE.finditer(text):
            iface = Interface(m["name"], m["base"])
            for mm in METHOD_RE.finditer(m["body"]):
                iface.methods.append((" ".join(mm["ret"].split()), mm["name"], " ".join(mm["params"].split())))
            out[iface.name] = iface
    return out


def flatten(ifaces: dict[str, Interface], name: str) -> list[tuple[str, str, str]]:
    if name == "IUnknown":
        return [("HRESULT", "QueryInterface", ""), ("ULONG", "AddRef", ""), ("ULONG", "Release", "")]
    iface = ifaces.get(name)
    if iface is None:
        raise KeyError(name)
    return flatten(ifaces, iface.base) + iface.methods


def parse_types() -> dict[str, str]:
    """Type name -> 'enum', 'struct', 'pointer' or the base type it aliases."""
    types: dict[str, str] = {}
    sources = list(idl_files()) + sorted(ROOT.glob("*.h"))
    for path in sources:
        text = re.sub(r"/\*.*?\*/", "", path.read_text(), flags=re.S)
        for m in re.finditer(r"typedef\s+(enum|struct|union)\s+(\w+)\s*\{.*?\}\s*(\w+)\s*;", text, re.S):
            types[m.group(3)] = "enum" if m.group(1) == "enum" else "struct"
            types[m.group(2)] = types[m.group(3)]
        for m in re.finditer(r"typedef\s+(enum|struct|union)\s+(\w+)\s*$", text, re.M):
            types[m.group(2)] = "enum" if m.group(1) == "enum" else "struct"
        for m in re.finditer(r"typedef\s+(struct|union)\s+(\w+)\s*\*\s*(\w+)\s*;", text):
            types[m.group(3)] = "pointer"
            types.setdefault(m.group(2), "struct")
        for m in re.finditer(r"typedef\s+(struct|union)\s+(\w+)\s+(\w+)\s*;", text):
            types[m.group(3)] = "struct"
        for m in re.finditer(r"typedef\s+([A-Z_][A-Za-z0-9_]*)\s+(\w+)\s*;", text):
            if m.group(1) not in ("enum", "struct", "union"):
                types.setdefault(m.group(2), m.group(1))
    return types


# ---------------------------------------------------------------------------------------------
# Trace format strings, Wine style

INT_FORMATS = {
    "BOOLEAN": "%d", "BOOL": "%d", "int": "%d", "INT": "%d", "INT8": "%d", "INT16": "%d", "INT32": "%d",
    "UINT8": "%u", "UINT16": "%u", "UINT32": "%u", "UINT": "%u", "BYTE": "%u", "WORD": "%u",
    "LONG": "%ld", "ULONG": "%lu", "DWORD": "%lu", "HRESULT": "%#lx",
    "INT64": "%I64d", "LONG64": "%I64d", "UINT64": "%I64u", "ULONG64": "%I64u", "time_t": "%I64u",
    "SIZE_T": "%Iu", "size_t": "%Iu", "float": "%f", "double": "%f", "char": "%d", "WCHAR": "%d",
}


def trace_arg(typ: str, name: str, types: dict[str, str]) -> tuple[str, str]:
    t = typ.replace("const ", "").strip()
    if t == "XTaskQueueRegistrationToken":
        return "%I64u", f"{name}.token"
    if t in ("char *",):
        return "%s", f"debugstr_a( {name} )"
    if t in ("WCHAR *", "LPCWSTR", "LPWSTR"):
        return "%s", f"debugstr_w( {name} )"
    if t.endswith("*"):
        return "%p", name
    seen = set()
    while t in types and t not in INT_FORMATS and t not in seen:
        seen.add(t)
        kind = types[t]
        if kind == "enum":
            return "%d", name
        if kind == "pointer":
            return "%p", name
        if kind == "struct":
            return "%p", f"&{name}"
        t = kind
    if t in INT_FORMATS:
        return INT_FORMATS[t], name
    if t.endswith("Handle") or t in ("HANDLE", "HWND", "HMODULE"):
        return "%p", name
    return "%p", f"&{name}"  # unknown by-value type: print its address, always valid C


def trace_call(macro: str, params: list[tuple[str, str]], types: dict[str, str], suffix: str) -> str:
    fmts, args = [], []
    for typ, name in params:
        fmt, arg = trace_arg(typ, name, types)
        fmts.append(f"{name} {fmt}")
        args.append(arg)
    fmt = ", ".join(fmts) + suffix + "\\n"
    return f'    {macro}( "{fmt}"' + "".join(f", {a}" for a in args) + " );\n"


def default_return(ret: str) -> str | None:
    ret = ret.strip()
    if ret == "void":
        return None
    if ret in ("HRESULT",):
        return "E_NOTIMPL"
    if ret in ("BOOLEAN", "BOOL"):
        return "FALSE"
    if ret.endswith("*") or ret.endswith("Handle"):
        return "NULL"
    return "0"


# ---------------------------------------------------------------------------------------------
# Commands


def stub_kind(method: str) -> str:
    if re.match(r"^X\w*?Unregister", method):
        return "unregister"
    if re.match(r"^X\w*?Register", method):
        return "register"
    if method.endswith("Async"):
        return "async"
    if method.endswith("Result") or method.endswith("ResultSize"):
        return "result"
    return "other"


def load_events() -> list[dict]:
    if not EVENTS.exists():
        return []
    return tomllib.loads(EVENTS.read_text()).get("never_fires", [])


def cmd_report(logs: list[str]) -> int:
    hits: Counter[str] = Counter()
    for log in logs:
        for m in re.finditer(r"fixme:gdkc:(x_\w+)", Path(log).read_text(errors="replace")):
            hits[m.group(1)] += 1
    event_names = {e[k] for e in load_events() for k in ("register", "unregister") if k in e}
    funcs = [f for f in all_functions() if f.is_stub]
    funcs.sort(key=lambda f: (-hits[f.name], f.path.name, f.start))
    kinds = Counter(stub_kind(f.method) for f in funcs)
    print(f"# xgameruntime stubs\n\n{len(funcs)} stubs: " + ", ".join(f"{n} {k}" for k, n in kinds.most_common()) + ".")
    if logs:
        hit = [f for f in funcs if hits[f.name]]
        print(f"{len(hit)} of them were hit in {len(logs)} log(s).")
    print("\n| Hits | File | Method | Kind | Note |\n|---:|---|---|---|---|")
    for f in funcs:
        note = "listed in events.toml" if f.method in event_names else ""
        print(f"| {hits[f.name] or ''} | {f.path.name} | `{f.method}` | {stub_kind(f.method)} | {note} |")
    return 0


def vtables():
    for path in c_files():
        text = path.read_text()
        for m in VTBL_RE.finditer(text):
            body = re.sub(r"/\*.*?\*/", "", m["body"], flags=re.S)
            entries = [e.strip() for e in body.split(",") if e.strip()]
            yield path, m["iface"], entries, m


def entry_matches(entry: str, method: str) -> bool:
    """The IDL repeats a name for each overload version; C adds a number (XFoo2, XFoo3)."""
    if entry.startswith("__PADDING") and method.startswith("__PADDING"):
        return True
    return re.search(rf"(?:^|_){re.escape(method)}\d*$", entry) is not None


def missing_methods(ifaces, iface: str, entries: list[str]):
    """(prefix, missing tail methods, problems) for one vtable."""
    methods = flatten(ifaces, iface)
    problems = []
    for i, (entry, (_, method, _)) in enumerate(zip(entries, methods)):
        if not entry_matches(entry, method):
            problems.append(f"slot {i}: C has {entry}, IDL has {method}")
    if len(entries) > len(methods):
        problems.append(f"C has {len(entries) - len(methods)} entries more than the IDL")
    prefix = ""
    for entry, (_, method, _) in zip(entries, methods):
        if entry.endswith("_" + method):
            prefix = entry[: -len(method)]
            break
    return prefix, methods[len(entries) :], problems


def cmd_check() -> int:
    ifaces = parse_interfaces()
    bad = 0
    for path, iface, entries, _ in vtables():
        try:
            _, missing, problems = missing_methods(ifaces, iface, entries)
        except KeyError as e:
            print(f"{path.name}: {iface}: interface {e} not found in the IDL files")
            bad += 1
            continue
        for p in problems:
            print(f"{path.name}: {iface}: {p}")
            bad += 1
        if missing:
            print(f"{path.name}: {iface}: {len(missing)} IDL methods missing at the end: "
                  + ", ".join(m[1] for m in missing))
            bad += 1
    print("check ok" if not bad else f"{bad} problem(s)")
    return 1 if bad else 0


def generate_stub(iface: str, prefix: str, ret: str, method: str, params: str, types) -> str:
    plist = split_params(params)
    struct_ret = types.get(ret) == "struct"
    if struct_ret:
        # widl returns structs through a hidden pointer: `T *method( iface, T *__ret )`.
        plist = plist + [(f"{ret} *", "__ret")]
    c_ret = f"{ret}*" if struct_ret else ret
    head = f"static {c_ret} WINAPI {prefix}{method}( {iface} *iface" + "".join(f", {t if t.endswith('*') else t + ' '}{n}".replace("* ", "*") for t, n in plist) + " )\n{\n"
    body = trace_call("FIXME", [(f"{iface} *", "iface")] + plist, types, " stub!")
    if struct_ret:
        body += "    memset( __ret, 0, sizeof(*__ret) );\n    return __ret;\n"
    elif (r := default_return(ret)) is not None:
        body += f"    return {r};\n"
    return head + body + "}\n"


def cmd_stubs(write: bool) -> int:
    ifaces = parse_interfaces()
    types = parse_types()
    total = 0
    done: set[str] = set()
    while True:
        # Re-scan after every write: inserting code moves the other vtables of the same file.
        todo = None
        for path, iface, entries, m in vtables():
            if iface in done:
                continue
            prefix, missing, problems = missing_methods(ifaces, iface, entries)
            if missing and problems:
                print(f"{path.name}: {iface}: skipped, fix `check` problems first", file=sys.stderr)
            elif missing:
                todo = (path, iface, prefix, missing, m)
                break
            done.add(iface)
        if todo is None:
            break
        path, iface, prefix, missing, m = todo
        done.add(iface)
        # The IDL repeats a name for each overload version; C needs unique names (XFoo2, XFoo3).
        taken = {f.name for f in parse_functions(path)}
        named = []
        for r, n, p in missing:
            name, i = n, 2
            while prefix + name in taken:
                name, i = f"{n}{i}", i + 1
            taken.add(prefix + name)
            named.append((r, name, p))
        missing = named
        code = "\n".join(generate_stub(iface, prefix, r, n, p, types) for r, n, p in missing)
        total += len(missing)
        if not write:
            print(f"/* {path.name}: {iface} */\n{code}")
            continue
        text = path.read_text()
        vstart = text.rfind("static const struct", 0, m.end())
        vend = text.index("};", vstart)
        insert = "".join(f"    {prefix}{n},\n" for _, n, _ in missing)
        text = text[:vend] + insert + text[vend:]
        text = text[:vstart] + code + "\n" + text[vstart:]
        path.write_text(text)
        print(f"{path.name}: {iface}: added {len(missing)} stubs")
    if not total:
        print("no missing methods")
    return 0


def find_function(funcs: list[Function], method: str) -> Function | None:
    found = [f for f in funcs if f.method == method]
    return found[0] if len(found) == 1 else None


def trace_from_body(f: Function, types) -> str:
    m = re.search(r"^    (?:FIXME|TRACE)\( (\".*?\")(.*?) \);\n", f.body, re.M)
    if m:
        fmt = m.group(1).replace(" stub!", "").replace("\\n\"", ".\\n\"")
        fmt = fmt.replace("..\\n", ".\\n")
        return f"    TRACE( {fmt}{m.group(2)} );\n"
    iface = split_params(f.params)
    return trace_call("TRACE", iface, types, ".")


def register_body(f: Function, reason: str, types, require: list[str]) -> str:
    params = split_params(f.params)
    callback = next((n for t, n in params if "Callback" in t), None)
    token = next((n for t, n in params if t.replace(" ", "") == "XTaskQueueRegistrationToken*"), None)
    if not callback or not token or f.ret != "HRESULT":
        raise ValueError(f"{f.name}: not a (queue, context, callback, token) registration")
    names = {n for _, n in params}
    for r in require:
        if r not in names:
            raise ValueError(f"{f.name}: required parameter {r} does not exist")
    checks = " || ".join(f"!{n}" for n in [*require, callback, token])
    return (
        f"    {MARKER}\n"
        "    static LONG64 next_token;\n\n"
        + trace_from_body(f, types)
        + f"\n    if ({checks}) return E_INVALIDARG;\n"
        + block_comment(reason)
        + f"    {token}->token = InterlockedIncrement64( &next_token );\n"
        "    return S_OK;\n}\n"
    )


def unregister_body(f: Function, types) -> str:
    params = split_params(f.params)
    if f.ret != "BOOLEAN" or not any(t == "XTaskQueueRegistrationToken" for t, _ in params):
        raise ValueError(f"{f.name}: not an unregistration taking a token")
    trace = trace_call("TRACE", params, types, ".")
    return f"    {MARKER}\n" + trace + "    return TRUE;\n}\n"


def block_comment(text: str) -> str:
    lines = wrap(text)
    out = f"    /* {lines[0]}"
    for line in lines[1:]:
        out += f"\n     * {line}"
    return out + " */\n"


def wrap(text: str, width: int = 92) -> list[str]:
    words, lines, cur = text.split(), [], ""
    for w in words:
        if cur and len(cur) + 1 + len(w) > width:
            lines.append(cur)
            cur = w
        else:
            cur = f"{cur} {w}".strip()
    if cur:
        lines.append(cur)
    return lines


def cmd_events(write: bool) -> int:
    types = parse_types()
    events = load_events()
    changes: dict[Path, list[tuple[Function, str]]] = {}
    done: set[str] = set()
    errors = 0
    funcs = all_functions()
    for ev in events:
        for key in ("register", "unregister"):
            if key not in ev or ev[key] in done:
                continue  # several registrations can share one unregistration
            done.add(ev[key])
            f = find_function(funcs, ev[key])
            if f is None:
                print(f"{ev[key]}: not found (or not unique)", file=sys.stderr)
                errors += 1
                continue
            if not f.is_stub and not f.generated:
                print(f"{ev[key]}: hand-written implementation, left alone", file=sys.stderr)
                continue
            try:
                body = (register_body(f, ev["reason"], types, ev.get("require", [])) if key == "register"
                        else unregister_body(f, types))
            except ValueError as e:
                print(e, file=sys.stderr)
                errors += 1
                continue
            if body != f.body:
                changes.setdefault(f.path, []).append((f, body))
    for path, items in changes.items():
        print(f"{path.name}: " + ", ".join(f.method for f, _ in items))
        if write:
            text = path.read_text()
            for f, body in sorted(items, key=lambda x: -x[0].body_start):
                text = text[: f.body_start] + body + text[f.end :]
            path.write_text(text)
    if not changes and not errors:
        print("events up to date")
    elif not write:
        print("(dry run, use --write)")
        return 1  # the code is out of date with events.toml; the CI fails on this
    return 1 if errors else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("report")
    r.add_argument("logs", nargs="*")
    sub.add_parser("check")
    s = sub.add_parser("stubs")
    s.add_argument("--write", action="store_true")
    e = sub.add_parser("events")
    e.add_argument("--write", action="store_true")
    a = ap.parse_args()
    if a.cmd == "report":
        return cmd_report(a.logs)
    if a.cmd == "check":
        return cmd_check()
    if a.cmd == "stubs":
        return cmd_stubs(a.write)
    return cmd_events(a.write)


if __name__ == "__main__":
    sys.exit(main())
